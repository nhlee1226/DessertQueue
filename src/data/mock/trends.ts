function history(base: number[], ): { date: string; score: number }[] {
  const today = new Date("2026-11-17");
  return base.map((score, i) => {
    const d = new Date(today);
    d.setDate(today.getDate() - (base.length - 1 - i));
    return { date: d.toISOString().slice(0, 10), score };
  });
}

